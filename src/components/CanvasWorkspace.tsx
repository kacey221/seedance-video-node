  // Helper 1: AI chroma remover for Cutout
  const removeMagentaBackground = (srcBase64: string): Promise<string> => {
    return new Promise((resolve) => {
      const img = new Image();
      img.crossOrigin = 'anonymous';
      img.onload = () => {
        const canvas = document.createElement('canvas');
        canvas.width = img.width;
        canvas.height = img.height;
        const ctx = canvas.getContext('2d');
        if (!ctx) {
          resolve(srcBase64);
          return;
        }
        ctx.drawImage(img, 0, 0);
        const imgData = ctx.getImageData(0, 0, canvas.width, canvas.height);
        const data = imgData.data;
        
        // Loop through pixels and wipe close-to-magenta pixels into fully transparent
        for (let i = 0; i < data.length; i += 4) {
          const r = data[i];
          const g = data[i + 1];
          const b = data[i + 2];
          
          // Pure magenta is RGB(255, 0, 255).
          const isMagenta = r > 150 && g < 110 && b > 150 && Math.abs(r - b) < 95;
          if (isMagenta) {
            data[i + 3] = 0; // Translucent alpha
          }
        }
        ctx.putImageData(imgData, 0, 0);
        resolve(canvas.toDataURL('image/png'));
      };
      img.onerror = () => resolve(srcBase64);
      img.src = srcBase64;
    });
  };

  // Helper 2: Expand image to add black borders for Outpainting
  const createPaddedImage = (srcBase64: string, direction: 'left' | 'right' | 'up' | 'down' | 'all'): Promise<string> => {
    return new Promise((resolve) => {
      const img = new Image();
      img.crossOrigin = 'anonymous';
      img.onload = () => {
        const canvas = document.createElement('canvas');
        const w = img.width;
        const h = img.height;
        
        let newW = w;
        let newH = h;
        let offsetX = 0;
        let offsetY = 0;
        
        if (direction === 'left') {
          newW = Math.round(w * 1.5);
          offsetX = Math.round(w * 0.5);
        } else if (direction === 'right') {
          newW = Math.round(w * 1.5);
        } else if (direction === 'up') {
          newH = Math.round(h * 1.5);
          offsetY = Math.round(h * 0.5);
        } else if (direction === 'down') {
          newH = Math.round(h * 1.5);
        } else if (direction === 'all') {
          newW = Math.round(w * 1.4);
          newH = Math.round(h * 1.4);
          offsetX = Math.round(w * 0.2);
          offsetY = Math.round(h * 0.2);
        }
        
        canvas.width = newW;
        canvas.height = newH;
        const ctx = canvas.getContext('2d');
        if (!ctx) {
          resolve(srcBase64);
          return;
        }
        
        // Clean deep dark background for visual contrast
        ctx.fillStyle = '#1e1e24';
        ctx.fillRect(0, 0, newW, newH);
        ctx.drawImage(img, offsetX, offsetY, w, h);
        resolve(canvas.toDataURL('image/png'));
      };
      img.onerror = () => resolve(srcBase64);
      img.src = srcBase64;
    });
  };

